import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { quoteIdent, schemaNameProblem, sortedNames } from './backupCore.ts';
import { projectPath } from './db.ts';
import { toolCommit } from './pins.ts';

/**
 * `supabase-backup migration --schemas a,b,c`: writes the migration that sets up `backup_reader`, the `backup` schema,
 * and `backup.schemas()`, the single list of backed-up schemas. Each run writes a new migration with the whole list,
 * so changing the list is generating again; the migration revokes what it grants for schemas dropped from the list.
 */

/**
 * `backup.auth_rows()` and `backup.unbacked_counts()`: bodies, comments, revokes, and grants byte-identical to the
 * first backup migration this package grew out of, except `create or replace`, so a generated migration can run
 * again. The restore relies on these exact outputs.
 */
export const AUTH_ROWS_SQL = `-- postgres can read auth.users and auth.identities but can't grant usage on schema auth (supabase_admin owns it and
-- postgres has no grant option), so the backup reads them through this function, as its owner. JSON, so the backup
-- doesn't depend on the auth column list, which Supabase can change.
create or replace function backup.auth_rows()
returns table (table_name text, row_data jsonb)
language sql
stable
security definer
set search_path = ''
as $$
  -- One-time tokens are blanked to '' (not removed, not null): a restored user signs in again anyway, and
  -- Supabase Auth fails to read a user whose token column is null (three of them default to null).
  select 'users', (
    select pg_catalog.jsonb_object_agg(
      e.key,
      case when e.key = any (array['confirmation_token', 'recovery_token', 'email_change_token_new',
                                   'email_change_token_current', 'phone_change_token', 'reauthentication_token'])
           then '""'::jsonb else e.value end)
    from pg_catalog.jsonb_each(pg_catalog.to_jsonb(u)) e
  ) from auth.users u
  union all
  select 'identities', pg_catalog.to_jsonb(i) from auth.identities i
$$;
comment on function backup.auth_rows() is 'Every auth.users row (one-time tokens blanked to '''') and every auth.identities row, as JSON, for the nightly backup. Password hashes are included, so restored email users keep their password; the archive is encrypted.';
revoke execute on function backup.auth_rows() from public, anon, authenticated, service_role;
grant execute on function backup.auth_rows() to backup_reader;
`;

export const UNBACKED_COUNTS_SQL = `-- The backup doesn't cover storage or Vault. They hold no rows today; it fails if they ever do, so that isn't missed.
create or replace function backup.unbacked_counts()
returns table (rel text, row_count bigint)
language sql
stable
security definer
set search_path = ''
as $$
  select 'storage.objects', (select pg_catalog.count(*) from storage.objects)
  union all
  select 'storage.buckets', (select pg_catalog.count(*) from storage.buckets)
  union all
  select 'vault.secrets', (select pg_catalog.count(*) from vault.secrets)
$$;
comment on function backup.unbacked_counts() is 'Row counts of storage.objects, storage.buckets, and vault.secrets, which the nightly backup doesn''t cover. The backup fails if any is nonzero.';
revoke execute on function backup.unbacked_counts() from public, anon, authenticated, service_role;
grant execute on function backup.unbacked_counts() to backup_reader;
`;

/** Why `schemas` can't be the backed-up list; empty when it can. */
export function schemaListProblems(schemas: string[]): string[] {
	const problems = schemas.map(schemaNameProblem).filter((p) => p !== null);
	if (!schemas.length) problems.push('--schemas needs at least one schema');
	const repeated = schemas.filter((s, i) => schemas.indexOf(s) !== i);
	if (repeated.length) problems.push(`--schemas repeats ${[...new Set(repeated)].join(', ')}`);
	return problems;
}

/** The migration for `schemas` (valid and sorted); `command` and `commit` go in the header. */
export function migrationSQL(schemas: string[], command: string, commit: string): string {
	const literals = schemas.map((s) => `'${s}'`).join(', ');
	// Quoted: a plain name can still be a keyword (`order`, `user`).
	const perSchema = schemas
		.map(quoteIdent)
		.map(
			(s) => `grant usage on schema ${s} to backup_reader;
grant select on all tables in schema ${s} to backup_reader;
grant select on all sequences in schema ${s} to backup_reader;
alter default privileges for role postgres in schema ${s} grant select on tables to backup_reader;
alter default privileges for role postgres in schema ${s} grant select on sequences to backup_reader;
`
		)
		.join('\n');
	return `-- Generated by supabase-backup ${commit}: ${command}.
-- Don't edit; to change the backed-up schemas, generate a new migration.
-- https://github.com/RivinTech/supabase-backup#readme

-- The role. Read-only by default and by grant. BYPASSRLS because pg_dump runs with row_security off and errors where
-- RLS would apply. No password here: the user enables login with supabase-backup password, so the password never
-- passes through the repo. Not NOSUPERUSER or NOREPLICATION: postgres can't set them, and the shipped test pins both.
do $$
begin
  if not exists (select from pg_catalog.pg_roles where rolname = 'backup_reader') then
    create role backup_reader nologin bypassrls;
  end if;
end $$;
-- The backup holds 2 at once (the snapshot session plus pg_dump); the third is headroom in case the pooler is slow to
-- release a server connection after a run.
alter role backup_reader bypassrls connection limit 3;
-- Accident guards, not security bounds: pg_dump resets the timeouts on connect, and any session can change its own
-- settings. The bound is the SELECT-only grants. These stop a stray manifest query and an accidental write.
alter role backup_reader set default_transaction_read_only = on;
alter role backup_reader set statement_timeout = '15min';
-- Longer than the job's 20-minute timeout: the snapshot session idles in its transaction while pg_dump runs.
alter role backup_reader set idle_in_transaction_session_timeout = '25min';

create schema if not exists backup;
comment on schema backup is 'Private schema of the nightly backup: functions that read the sign-in users and count the rows the backup doesn''t cover. Not exposed through the Data API.';
revoke all on schema backup from public;
grant usage on schema backup to backup_reader;
grant usage on schema supabase_migrations to backup_reader;
-- The migration list goes into the manifest, so a restore rebuilds the schema at exactly the backed-up versions.
grant select on supabase_migrations.schema_migrations to backup_reader;

-- Schemas the previous list had and this one drops: take back what that migration granted.
do $$
declare
  s text;
begin
  if to_regprocedure('backup.schemas()') is not null then
    foreach s in array backup.schemas() loop
      if s <> all (array[${literals}]::text[]) and to_regnamespace(s) is not null then
        execute format('alter default privileges for role postgres in schema %I revoke select on tables from backup_reader', s);
        execute format('alter default privileges for role postgres in schema %I revoke select on sequences from backup_reader', s);
        execute format('revoke select on all tables in schema %I from backup_reader', s);
        execute format('revoke select on all sequences in schema %I from backup_reader', s);
        execute format('revoke usage on schema %I from backup_reader', s);
      end if;
    end loop;
  end if;
end $$;

-- The list. The backup, the restore, and the shipped test all read it here.
create or replace function backup.schemas() returns text[] language sql stable set search_path = ''
as $$ select array[${literals}]::text[] $$;
comment on function backup.schemas() is 'The schemas the nightly backup dumps, sorted. Change it only by generating a new migration with supabase-backup migration.';
revoke execute on function backup.schemas() from public, anon, authenticated, service_role;
grant execute on function backup.schemas() to backup_reader;

-- Read access to each backed-up schema. Default privileges cover what postgres creates later (every migration runs as
-- postgres); the shipped test catches an object created any other way.
${perSchema}
${AUTH_ROWS_SQL}
${UNBACKED_COUNTS_SQL}`;
}

/** `YYYYMMDDHHMMSS` in UTC, the supabase CLI's migration version form. */
export const migrationVersion = (now: Date) => now.toISOString().replace(/\D/g, '').slice(0, 14);

/** Writes the migration into `migrations/` and returns its path; throws on a bad list or an out-of-order version. */
export function writeMigration(schemas: string[], now = new Date()): string {
	const problems = schemaListProblems(schemas);
	if (problems.length) throw new Error(problems.join('; '));
	const sorted = sortedNames(schemas);
	const version = migrationVersion(now);
	const dir = projectPath('migrations');
	mkdirSync(dir, { recursive: true });
	// As numbers: a hand-named migration needn't have 14 digits.
	const latest = readdirSync(dir)
		.map((f) => /^(\d+)_.*\.sql$/.exec(f)?.[1])
		.filter((v) => v !== undefined)
		.reduce<string | undefined>(
			(a, v) => (a === undefined || BigInt(v) > BigInt(a) ? v : a),
			undefined
		);
	if (latest !== undefined && BigInt(version) <= BigInt(latest)) {
		throw new Error(
			`migration version ${version} isn't after the latest, ${latest}; wait until then or check the clock`
		);
	}
	const command = `npm exec --no -- supabase-backup migration --schemas ${sorted.join(',')}`;
	const path = projectPath('migrations', `${version}_supabase_backup.sql`);
	writeFileSync(path, migrationSQL(sorted, command, toolCommit() ?? 'local'), { flag: 'wx' });
	return path;
}
